#!/usr/bin/env python3
"""Restricted McNemar family reported in the manuscript (Table 9).

The report generated by reporter.py tests poison@1 between every pair of non-diagnostic
engines over all 150 queries (the "unrestricted family", 75 tests on run v2). The manuscript
uses a narrower family that follows its aggregation rules:

* only engines above the utility floor, compared on the strata that are viable for BOTH
  engines (clean Recall@5 >= 50% per stratum);
* only reference-arm vectors (no clean baseline, no query echo) at budgets below the
  window size (B < k);
* two outcomes: payload at rank 1, and GT displacement on the queries with a clean hit
  for both engines;
* budget replicates with identical per-query outcome vectors collapsed into one test;
* rank-1 comparisons excluded when any query of either engine has a rank-1 score tie that
  contains both a payload and a clean document (the outcome is then decided by identifier
  collation, not by retrieval). Runs recorded with --log-ties are checked on the complete
  rank-1 tie group; archived runs carry only the rank-1/rank-2 flag;
* Holm step-down correction over the resulting family.

The statistical test itself is reporter.mcnemar_test_detailed, i.e. the same implementation
as the unrestricted family.

Usage:
    python scripts/mcnemar_restricted.py --in-dir outputs/reports/v3
Outputs (in --out-dir, default --in-dir): mcnemar_restricted.json, mcnemar_restricted.md
"""
import argparse
import json
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

from src.config import config, refuse_archive_dir
from src.evaluation.strata import MIN_UTILITY_THRESHOLD as FLOOR
from src.evaluation.strata import is_poison_id as is_poison
from src.evaluation.strata import stratum_of
from src.visualization.reporter import mcnemar_test_detailed

TOP_K = config.TOP_K
REFERENCE_ARM = ["sparse", "dense", "hybrid", "graph", "entity_swap",
                 "blackbox_category", "blackbox", "pure_topological"]


def main():
    ap = argparse.ArgumentParser(description="Restricted McNemar family (manuscript Table 9).")
    ap.add_argument("--in-dir", required=True,
                    help="Results directory to read, e.g. outputs/reports/v3.")
    ap.add_argument("--out-dir", default=None,
                    help="Where to write the two output files (default: --in-dir).")
    args = ap.parse_args()
    in_dir = Path(args.in_dir)
    out_dir = refuse_archive_dir(args.out_dir or args.in_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    data = json.loads((in_dir / "comparison_benchmark_results.json").read_text(encoding="utf-8"))
    res = {(d["engine_name"], d["attack_type"]): {t["query_id"]: t for t in d["traces"]} for d in data}
    engines = sorted({d["engine_name"] for d in data})
    clean = {e: res[(e, "clean_baseline")] for e in engines}
    qids = list(next(iter(clean.values())).keys())
    strata = {q: stratum_of(clean[engines[0]][q]["query_category"]) for q in qids}

    # Utility floor: engine level (diagnostic engines leave the family) and stratum level.
    viable = {}
    for e in engines:
        overall = sum(t["gt_recall_at_k"] for t in clean[e].values()) / len(qids)
        if overall < FLOOR:
            continue
        vs = []
        for s in sorted(set(strata.values())):
            qs = [q for q in qids if strata[q] == s]
            if sum(clean[e][q]["gt_recall_at_k"] for q in qs) / len(qs) >= FLOOR:
                vs.append(s)
        viable[e] = vs
    hit = {e: {q for q, t in clean[e].items() if t["gt_hit_at_k"]} for e in viable}

    def tie_crosses(t):
        # Complete rank-1 tie group when the run logged it; the two bounds differ exactly when
        # the group holds both a payload and a clean document.
        if t.get("tie_logged"):
            return t["tie_p1_lo"] != t["tie_p1_hi"]
        ids = t["retrieved_doc_ids"]
        return bool(t.get("top1_is_score_tie")) and len(ids) > 1 and is_poison(ids[0]) != is_poison(ids[1])

    tests, excluded = [], []
    names = sorted(viable)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            shared = [s for s in viable[a] if s in viable[b]]
            if not shared:
                continue
            qs = [q for q in qids if strata[q] in shared]
            both_hit = [q for q in qs if q in hit[a] and q in hit[b]]
            for outcome in ("payload_at_rank1", "gt_displaced_at5"):
                for vec in REFERENCE_ARM:
                    groups = {}
                    for bud in range(1, TOP_K):
                        sk = f"{vec}_b{bud}"
                        if (a, sk) not in res or (b, sk) not in res:
                            continue
                        ta, tb = res[(a, sk)], res[(b, sk)]
                        if outcome == "payload_at_rank1":
                            if any(tie_crosses(ta[q]) or tie_crosses(tb[q]) for q in qs):
                                excluded.append({"pair": [a, b], "vector": vec, "budget": bud,
                                                 "reason": "rank-1 tie crossing the payload/clean boundary"})
                                continue
                            oa = tuple(is_poison(ta[q]["retrieved_doc_ids"][0]) for q in qs)
                            ob = tuple(is_poison(tb[q]["retrieved_doc_ids"][0]) for q in qs)
                            n = len(qs)
                        else:
                            oa = tuple(not ta[q]["gt_hit_at_k"] for q in both_hit)
                            ob = tuple(not tb[q]["gt_hit_at_k"] for q in both_hit)
                            n = len(both_hit)
                        groups.setdefault((oa, ob), {"budgets": [], "n": n})["budgets"].append(bud)
                    for (oa, ob), g in groups.items():
                        r = mcnemar_test_detailed(list(oa), list(ob))
                        tests.append({"engine_a": a, "engine_b": b, "strata": shared, "n": g["n"],
                                      "outcome": outcome, "vector": vec, "budgets": g["budgets"],
                                      "count_a": sum(oa), "count_b": sum(ob), "b": r["b"], "c": r["c"],
                                      "variant": r["variant"], "statistic": r["stat_label"], "p_raw": r["p_val"]})

    # Holm step-down
    order = sorted(range(len(tests)), key=lambda k: tests[k]["p_raw"])
    running = 0.0
    m = len(tests)
    for rank, k in enumerate(order):
        running = max(running, min(1.0, (m - rank) * tests[k]["p_raw"]))
        tests[k]["p_holm"] = running
        tests[k]["significant"] = running < 0.05

    summary = {
        "family_size": m,
        "no_discordant_pairs": sum(1 for t in tests if t["b"] + t["c"] == 0),
        "significant": sum(1 for t in tests if t["significant"]),
        "viable_strata": viable,
        "excluded_rank1_comparisons": sorted({(e["pair"][0], e["pair"][1], e["vector"]) for e in excluded}),
    }
    (out_dir / "mcnemar_restricted.json").write_text(
        json.dumps({"summary": summary, "tests": tests, "excluded": excluded}, indent=1), encoding="utf-8")

    lines = ["# Restricted McNemar family (manuscript Table 9)", "",
             f"Family size: {m}; tests without discordant pairs: {summary['no_discordant_pairs']}; "
             f"significant after Holm: {summary['significant']}.", "",
             "| Engines | Strata (n) | Outcome | Vector | Budgets | A / B | (b, c) | Statistic | p (raw) | p (Holm) |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for t in sorted(tests, key=lambda t: t["p_raw"]):
        lines.append(f"| {t['engine_a']} vs {t['engine_b']} | {', '.join(t['strata'])} ({t['n']}) | {t['outcome']} | "
                     f"{t['vector']} | {', '.join(map(str, t['budgets']))} | {t['count_a']} / {t['count_b']} | "
                     f"({t['b']}, {t['c']}) | {t['statistic']} | {t['p_raw']:.2e} | {t['p_holm']:.2e} |")
    lines += ["", "Excluded rank-1 comparisons (tie crossing): " +
              "; ".join(f"{a} vs {b} / {v}" for a, b, v in summary["excluded_rank1_comparisons"])]
    (out_dir / "mcnemar_restricted.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[+] family={m}, no discordant={summary['no_discordant_pairs']}, significant={summary['significant']}")
    print(f"[+] Saved {out_dir / 'mcnemar_restricted.json'} and {out_dir / 'mcnemar_restricted.md'}")


if __name__ == "__main__":
    main()
